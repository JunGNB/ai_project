#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Verify / restore the raw assets of the performance test set.

    python tool/dataset/performance/fetch.py             # download missing files
    python tool/dataset/performance/fetch.py --verify    # read-only size+sha256 report
    python tool/dataset/performance/fetch.py --mirror https://hf-mirror.com

All upstream corpora are cached in ``dataset/raw`` (gitignored); this script
restores anything missing from the pinned upstream URL and always re-verifies
size/SHA-256 so the design document can quote a reproducible provenance table.
Derived assets (the cl100k tokenizer JSON) are regenerated by their own script.
Standard library only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Dict, List

PROJECT_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(PROJECT_ROOT))

from tool.dataset.performance.sources import SOURCES  # noqa: E402

LANGS = ("zh", "en", "fr", "de", "es", "pt", "ru", "ja", "ko", "ar")
CHUNK = 1 << 20


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def expand(spec: Dict) -> List[Dict]:
    """One (path, url) pair per concrete file; ``{lang}`` fans out to 10 languages."""
    raw = str(spec["path"])
    url = str(spec["url"])
    if "{lang}" not in raw:
        return [{"path": raw, "url": url, "license": spec.get("license"), "note": spec.get("note")}]
    out = []
    for lang in LANGS:
        out.append(
            {
                "path": raw.replace("{lang}", lang),
                "url": url.replace("{lang}", lang),
                "license": spec.get("license"),
                "note": f"{spec.get('note')} [{lang}]",
            }
        )
    return out


def mirror_url(url: str, mirror: str) -> str:
    if not mirror:
        return url
    if url.startswith("https://huggingface.co/"):
        return mirror.rstrip("/") + "/" + url[len("https://huggingface.co/") :]
    return url


def download(url: str, dest: Path, retries: int = 4) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_suffix(dest.suffix + ".part")
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "modelbench-perf/1.0"})
            with urllib.request.urlopen(req, timeout=120) as resp, part.open("wb") as fh:
                while True:
                    chunk = resp.read(CHUNK)
                    if not chunk:
                        break
                    fh.write(chunk)
            os.replace(part, dest)
            return
        except (urllib.error.URLError, urllib.error.HTTPError, OSError) as exc:
            part.unlink(missing_ok=True)
            if attempt == retries - 1:
                raise
            print(f"    retry {attempt + 1}/{retries - 1}: {exc}")
            time.sleep(2 + 2 * attempt)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw-dir", default=str(PROJECT_ROOT / "dataset" / "raw"))
    parser.add_argument("--mirror", default=os.environ.get("HUGGINGFACE_MIRROR", ""))
    parser.add_argument("--verify", action="store_true", help="report only, never write")
    parser.add_argument("--manifest", default="", help="write provenance JSON here")
    args = parser.parse_args(argv)

    raw_dir = Path(args.raw_dir)
    missing, report, failures = [], [], []
    for key, spec in SOURCES.items():
        for item in expand(spec):
            path = raw_dir / item["path"]
            if not path.is_file():
                missing.append((key, item, path))
                continue
            report.append(
                {
                    "source": key,
                    "path": item["path"],
                    "bytes": path.stat().st_size,
                    "sha256": sha256_file(path),
                    "url": item["url"],
                    "license": item["license"],
                }
            )

    generated_missing = [(k, i, p) for k, i, p in missing if SOURCES[k].get("generated")]
    missing = [(k, i, p) for k, i, p in missing if not SOURCES[k].get("generated")]

    if missing and not args.verify:
        for key, item, path in missing:
            url = mirror_url(item["url"], args.mirror)
            print(f"[fetch] {key}: {item['path']} <- {url}")
            download(url, path)
            report.append(
                {
                    "source": key,
                    "path": item["path"],
                    "bytes": path.stat().st_size,
                    "sha256": sha256_file(path),
                    "url": url,
                    "license": item["license"],
                }
            )
        missing = []

    if generated_missing and not args.verify:
        import subprocess  # noqa: PLC0415

        script = PROJECT_ROOT / "tool" / "dataset" / "performance" / "derive_cl100k.py"
        print(f"[derive] {script}")
        subprocess.run([sys.executable, str(script)], check=True)
        for key, item, path in list(generated_missing):
            if path.is_file():
                report.append(
                    {
                        "source": key,
                        "path": item["path"],
                        "bytes": path.stat().st_size,
                        "sha256": sha256_file(path),
                        "url": item["url"],
                        "license": item["license"],
                    }
                )
                generated_missing.remove((key, item, path))
    missing.extend(generated_missing)

    for entry in report:
        print(f"  [ok] {entry['source']:<12} {entry['bytes']:>12,} B  {entry['sha256'][:16]}…  {entry['path']}")
    for key, item, path in missing:
        print(f"  [MISS] {key}: {path}")
        failures.append(item["path"])

    if args.manifest:
        out = Path(args.manifest)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            json.dumps(
                {
                    "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
                    "raw_dir": str(raw_dir),
                    "mirror": args.mirror,
                    "files": sorted(report, key=lambda r: r["path"]),
                },
                ensure_ascii=False,
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        print(f"[manifest] {out}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
